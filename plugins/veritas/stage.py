#!/usr/bin/env python3
"""Prepare a signed HSR test copy with exact-build Veritas detours."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from patch import clone_app, closed, digest, read_app_info, require, run
from plugins.signature_resolver import resolve_app, save_evidence
from signatures import Image

PROFILE = json.loads(Path(__file__).with_name('hsr-4.7.0.json').read_text())
FRAMEWORK = Path('Frameworks/UnityFramework.framework')
CONTRACT = Path(__file__).with_name('signatures.json')


def words(*instructions):
    return struct.pack(f'<{len(instructions)}I', *instructions)


def address_in_x16(pc, target):
    pages = (target >> 12) - (pc >> 12)
    require(-(1 << 20) <= pages < (1 << 20), 'Detour address is out of range')
    return words(0x90000010 | (pages & 3) << 29 | ((pages >> 2) & 0x7ffff) << 5,
                 0x91000210 | (target & 0xfff) << 10)


def validate_prologue(expected):
    require(len(expected) == 12, 'Unsupported displaced instruction length')
    for (op,) in struct.iter_unpack('<I', expected):
        pair_store_sp = op & 0x3a4003e0 == 0x280003e0
        subtract_sp = op & 0xffc003ff == 0xd10003ff
        frame_pointer = op & 0xffc003ff == 0x910003fd
        require(pair_store_sp or subtract_sp or frame_pointer, 'Detour prologue is not relocatable stack setup')


def detours(profile=PROFILE):
    code = int(profile['code_padding'], 16)
    slots = int(profile['data_padding'], 16)
    for index, (name, (entry, expected)) in enumerate(profile['entries'].items()):
        entry, expected = int(entry, 16), bytes.fromhex(expected)
        require(entry % 4 == 0 and code % 4 == 0 and slots % 8 == 0 and len(expected) == 12, "Unaligned or unsupported detour")
        validate_prologue(expected)
        stub, slot = code + index * 48, slots + index * 8
        original = stub + 20
        entry_jump = address_in_x16(entry, stub) + words(0xd61f0200)
        # LDAR pairs with the plugin's release store. A missing plugin runs the original.
        stub_code = (address_in_x16(stub, slot) +
                     words(0xc8dffe10, 0xb4000050, 0xd61f0200) +
                     expected + address_in_x16(original + len(expected), entry + len(expected)) +
                     words(0xd61f0200))
        yield name, entry, expected, entry_jump, stub, slot, original, stub_code


def write_header(path, profile=PROFILE):
    lines = ['/* Generated by stage.py from the reviewed framework profile. */', '#ifndef VERITAS_PROFILE_H', '#define VERITAS_PROFILE_H']
    for name, entry, _, jump, stub, slot, original, code in detours(profile):
        for label, address in (('Entry', entry), ('Slot', slot), ('Original', original), ('Stub', stub)):
            lines.append(f'#define Veritas{name}{label} 0x{address:x}')
        ops = ', '.join(f'0x{word:x}' for (word,) in struct.iter_unpack('<I', jump))
        lines.append(f'static const uint32_t Veritas{name}Jump[] = {{ {ops} }};')
        stub_bytes = ', '.join(f'0x{byte:02x}' for byte in code)
        lines.append(f'static const uint8_t Veritas{name}Code[] = {{ {stub_bytes} }};')
    contract = json.loads(CONTRACT.read_text())
    for name in profile['methods']:
        rule = contract['functions'][name]
        check = rule.get('verify', rule)
        for label, data in [('Expected', bytes.fromhex(check['pattern'])), ('Mask', bytes.fromhex(check['mask']))]:
            values = ', '.join(f'0x{byte:02x}' for byte in data)
            lines.append(f'static const uint8_t Veritas{name}{label}[] = {{ {values} }};')
    for name, address in (profile['methods'] | profile['fields']).items():
        lines.append(f'#define Veritas{name} {address}')
    for name, number in profile.get('properties', {}).items():
        lines.append(f'#define VeritasProperty{name} {number}')
    for name, index in profile.get('types', {}).items():
        lines.append(f'#define VeritasType{name} {index}')
    fields = ', '.join(profile['damage_fields'])
    lines.append(f'static const unsigned VeritasDamageFields[] = {{ {fields} }};')
    for label, names in [('HOOKS', profile['entries']), ('METHODS', profile['methods'])]:
        lines.append(f'#define VERITAS_{label}(X) ' + ' '.join(f'X({name})' for name in names))
    lines.append('#endif')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n')


def instrument(binary, profile=PROFILE):
    require(hashlib.sha256(binary).hexdigest() in profile['framework_sha256'], 'Unsupported HSR framework hash')
    data = bytearray(binary)
    image = Image(data)
    require(next(vm for name, vm, _, _, _ in image.segments if name == "__TEXT") == 0, "Unexpected preferred image base")
    reserved, edits = [], []
    for name, entry, expected, jump, stub, slot, _, stub_code in detours(profile):
        require(entry in image.function_set and len(image.body(entry)) >= len(expected), f'{name} is no longer a function entry')
        for address, length in [(entry, len(jump)), (stub, len(stub_code)), (slot, 8)]:
            require(all(address + length <= start or start + size <= address for start, size in reserved), 'Overlapping detours')
            reserved.append((address, length))
        require(any(segment == '__DATA' and vm + stored <= slot and slot + 8 <= vm + size
                    for segment, vm, size, _, stored in image.segments),
                f'{name} callback is outside zero-filled writable storage')
        for segment, address, length in (('__TEXT', stub, len(stub_code)), ('__DATA', slot, 8)):
            require(all(s != segment or address + length <= start or start + size <= address
                        for (s, _), (start, size, _) in image.sections.items()),
                    f'{name} detour overlaps a game section')
        source = image.file(entry, len(expected), '__TEXT')
        target = image.file(stub, len(stub_code), '__TEXT')
        require(data[source:source + len(expected)] == expected, f'{name} entry changed')
        require(not any(data[target:target + len(stub_code)]), f'{name} stub padding is in use')
        edits.extend([(source, jump), (target, stub_code)])
    for offset, replacement in edits:
        data[offset:offset + len(replacement)] = replacement
    return data


def stage(app, output, with_plugin=True):
    info = read_app_info(app)
    require(info.get('CFBundleIdentifier') == PROFILE['bundle_id'] and
            info.get('CFBundleShortVersionString') == PROFILE['version'] and
            info.get('CFBundleExecutable') == PROFILE['executable'],
            'This preview supports the reviewed international HSR 4.7.0 build')
    require(output.suffix == '.app' and not output.exists() and
            output != app and app not in output.parents,
            'Choose a new .app output path outside the source app')
    closed(PROFILE)
    resolved, evidence = resolve_app(app, PROFILE, CONTRACT)
    evidence_path = save_evidence(evidence, PROFILE)
    source = app / FRAMEWORK / 'UnityFramework'
    require(source.resolve().is_relative_to(app), 'Framework points outside the source app')
    plugin = ROOT / 'build/plugins/VeritasLive.dylib'
    require(not with_plugin or plugin.is_file(), 'Build the Veritas plugin first with plugins/veritas/build.sh')
    output.parent.mkdir(parents=True, exist_ok=True)
    plan = output.with_suffix('.plan.json')
    require(not plan.exists(), 'A preview plan already exists')
    patched = instrument(source.read_bytes(), resolved)
    record = {"source_framework_sha256": evidence["framework_sha256"],
              "source_executable_sha256": digest(app / PROFILE['executable']),
              "planned_unsigned_framework_sha256": hashlib.sha256(patched).hexdigest(),
              "plugin_sha256": digest(plugin) if with_plugin else None,
              "resolution_report": str(evidence_path), "signature_contract_sha256": evidence["contract_sha256"], "status": "prepared"}
    with plan.open('x') as stream:
        stream.write(json.dumps(record, indent=2) + "\n")
    with tempfile.TemporaryDirectory(dir=output.parent) as directory:
        staged = Path(directory) / output.name
        clone_app(app, staged)
        framework = staged / FRAMEWORK
        binary = framework / 'UnityFramework'
        target = staged / 'Frameworks/UserPlugins/VeritasLive.dylib'
        require(all(path.resolve().is_relative_to(staged) for path in (binary, target)),
                'The game framework or plugin directory points outside the staged copy')
        require(not target.is_symlink(), 'The preview plugin path is a symbolic link')
        (target.parent / 'VeritasReports.dylib').unlink(missing_ok=True)
        if with_plugin:
            target.parent.mkdir(exist_ok=True)
            shutil.copy2(plugin, target)
            require(digest(target) == record['plugin_sha256'], 'Plugin changed while copying')
        else:
            target.unlink(missing_ok=True)
        require(digest(binary) == evidence["framework_sha256"], "Source changed while cloning")
        binary.write_bytes(patched)
        run('/usr/bin/codesign', '--force', '--sign', '-', '--preserve-metadata=entitlements', str(framework))
        run('/usr/bin/codesign', '--force', '--sign', '-', '--preserve-metadata=entitlements', str(staged))
        if with_plugin: run('/usr/bin/codesign', '--verify', '--strict', str(target))
        run('/usr/bin/codesign', '--verify', '--strict', str(staged))
        record.update(status='signed', signed_framework_sha256=digest(binary),
                      signed_executable_sha256=digest(staged / info['CFBundleExecutable']))
        plan.write_text(json.dumps(record, indent=2) + '\n')
        require(digest(source) == evidence['framework_sha256'], 'Source app changed during staging')
        require(digest(app / PROFILE['executable']) == record['source_executable_sha256'], 'Source executable changed during staging')
        require(not output.exists(), 'Output appeared during staging')
        staged.rename(output)
    print(f'Prepared Veritas preview at {output}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header', type=Path)
    parser.add_argument('--resolve', action='store_true', help='Print signature evidence without modifying the app')
    parser.add_argument('--app', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--without-plugin', action='store_true', help='Stage only the game hooks for manual plugin injection')
    args = parser.parse_args()
    if args.header and not (args.app or args.output or args.resolve or args.without_plugin):
        write_header(args.header)
    elif (args.header or args.resolve) and not (args.output or args.without_plugin):
        app = args.app or Path.home() / 'Library/Containers/io.playcover.PlayCover/Applications' / (PROFILE['bundle_id'] + '.app')
        profile, evidence = resolve_app(app, PROFILE, CONTRACT)
        if args.header: write_header(args.header, profile)
        else:
            save_evidence(evidence, PROFILE)
            print(json.dumps(evidence, indent=2))
    elif args.app and args.output and not (args.header or args.resolve):
        stage(args.app.resolve(), args.output.resolve(), not args.without_plugin)
    else:
        parser.error('Pass --app and --output to prepare a preview copy')


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        sys.exit(f'Veritas: {error}')
